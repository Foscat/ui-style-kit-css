import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const textElements = [
  'h1', 'h2', 'h3', 'h4', 'h5', 'h6', 'p', 'a', 'li', 'dt', 'dd',
  'figcaption', 'blockquote', 'label', 'legend', 'summary', 'strong', 'small',
  'em', 'code', 'kbd', 'samp', 'pre', 'th', 'td'
];

const wrapperSuffixes = [
  'page', 'container', 'section', 'stack', 'cluster', 'grid', 'split',
  'surface', 'surface-sm', 'surface-lg', 'card', 'card-service', 'card-feature',
  'panel', 'toolbar', 'well', 'inset', 'field', 'alert', 'table-wrap', 'nav',
  'feature-strip', 'feature-item', 'callout-bar', 'media-scrim'
];

const controlSuffixes = [
  'button', 'icon-button', 'button-cut', 'button-outline-heavy', 'badge',
  'badge-seal', 'nav-link', 'icon-medallion'
];

/**
 * Formats a selector list with stable indentation for the generated stylesheet.
 *
 * @param {string[]} selectors CSS selectors in release order.
 * @returns {string} A comma-separated selector block.
 */
function formatSelectors(selectors) {
  return selectors.map((selector) => `  ${selector}`).join(',\n');
}

/**
 * Expands preset prefixes and public suffixes into exact class-token selectors.
 *
 * @param {{prefix: string}[]} presets Manifest preset entries.
 * @param {string[]} suffixes Public class suffixes that share containment behavior.
 * @returns {string[]} Exact class-token selectors for every preset and suffix.
 */
function prefixedSelectors(presets, suffixes) {
  return presets.flatMap(({ prefix }) => suffixes.map((suffix) => `[class~="${prefix}-${suffix}"]`));
}

/**
 * Renders the shared content-overflow stylesheet from the public preset registry.
 *
 * @param {{presets: {prefix: string}[]}} manifest Public UI Style Kit manifest.
 * @returns {string} Complete generated CSS with a trailing newline.
 */
export function renderContentOverflowCss(manifest) {
  if (!Array.isArray(manifest?.presets) || manifest.presets.length === 0) {
    throw new TypeError('manifest.presets must contain at least one preset.');
  }

  const wrappers = prefixedSelectors(manifest.presets, wrapperSuffixes);
  const controls = prefixedSelectors(manifest.presets, controlSuffixes);

  return `/* =========================================================
   UI Style Kit CSS - Shared Content Overflow Contract

   Generated by scripts/generate-content-overflow.mjs from manifest.json.
   Text-bearing wrappers and controls shrink instead of widening the page.
========================================================= */

@layer ui-style-kit.content_overflow {
[data-ui][data-theme][data-mode] :where(
${formatSelectors(textElements)}
) {
  max-inline-size: 100%;
  min-inline-size: 0;
  overflow-wrap: break-word;
  word-break: normal;
}

[data-ui][data-theme][data-mode] :where(
${formatSelectors(wrappers)}
) {
  max-inline-size: 100%;
  min-inline-size: 0;
}

[data-ui][data-theme][data-mode] :where(
${formatSelectors(controls)}
) {
  max-inline-size: 100%;
  min-inline-size: 0;
  overflow-wrap: break-word;
  word-break: normal;
  white-space: normal;
}

}
`;
}

/**
 * Synchronizes the tracked standalone containment stylesheet with the manifest.
 *
 * @param {string} rootDir Repository root directory.
 * @param {{presets: {prefix: string}[]}} manifest Public UI Style Kit manifest.
 * @returns {string} Absolute path to the generated stylesheet.
 */
export function syncContentOverflowCss(rootDir, manifest) {
  const outputPath = path.join(rootDir, 'styles', 'content-overflow.css');
  fs.writeFileSync(outputPath, renderContentOverflowCss(manifest));
  return outputPath;
}

const currentFile = fileURLToPath(import.meta.url);
if (process.argv[1] && path.resolve(process.argv[1]) === currentFile) {
  const rootDir = path.resolve(path.dirname(currentFile), '..');
  const manifest = JSON.parse(fs.readFileSync(path.join(rootDir, 'manifest.json'), 'utf8'));
  syncContentOverflowCss(rootDir, manifest);
}
