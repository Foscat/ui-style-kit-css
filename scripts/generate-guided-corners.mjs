/**
 * @module scripts/generate-guided-corners
 * @description Generate opt-in, preset-independent control/surface geometry without changing authored defaults.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const values = { none: '0', small: '.25rem', medium: '.65rem', large: '1rem' };
const roles = [
  'surface',
  'surface-sm',
  'surface-lg',
  'card',
  'panel',
  'toolbar',
  'well',
  'inset',
  'alert',
  'table-wrap',
  'button',
  'icon-button',
  'input',
  'textarea',
  'select',
  'dialog',
  'modal',
  'nav-link',
];

/**
 * Build a closed opt-in geometry layer for native, canonical, compatibility and prefixed controls.
 * Omitting the attribute restores each preset; avatar and circular decoration roles are excluded.
 * @param {object} manifest Public preset and semantic namespace inventory.
 * @returns {string} Deterministic CSS with no changes to colors, layout, clipping, motion or defaults.
 */
export function guidedCornersCss(manifest) {
  const prefixes = [...new Set(['ui', 'usk', ...manifest.presets.map(({ prefix }) => prefix)])];
  const selectors = [
    'button',
    'input:not([type="checkbox"]):not([type="radio"]):not([type="range"])',
    'select',
    'textarea',
    'fieldset',
    'dialog',
    ...prefixes.flatMap((prefix) => roles.map((role) => `.${prefix}-${role}`)),
  ];
  const avatarClasses = prefixes.flatMap((prefix) => [
    `[class^="${prefix}-avatar"]`,
    `[class*=" ${prefix}-avatar"]`,
  ]);
  const scopes = Object.keys(values)
    .map((value) => `[data-usk-corners="${value}"]`)
    .join(', ');
  const declarations = Object.entries(values)
    .map(
      ([name, value]) =>
        `  [data-ui][data-mode][data-usk-corners="${name}"] {\n    --usk-guided-corner-radius: ${value};\n    --usk-native-radius: var(--usk-guided-corner-radius);\n    --usk-native-radius-sm: var(--usk-guided-corner-radius);\n    --usk-native-radius-lg: var(--usk-guided-corner-radius);\n    --usk-native-file-button-radius: var(--usk-guided-corner-radius);\n    --usk-native-color-swatch-radius: var(--usk-guided-corner-radius);\n  }`,
    )
    .join('\n\n');
  return `/* Generated by scripts/generate-guided-corners.mjs. Native and semantic geometry remain library owned. */\n@layer ui-style-kit.customization {\n${declarations}\n\n  [data-ui][data-mode]:is(${scopes}) :where(\n    ${selectors.join(',\n    ')}\n  ):where(:not(:is(${avatarClasses.join(', ')}))) {\n    border-radius: var(--usk-guided-corner-radius);\n  }\n}\n`;
}

/**
 * Synchronize the generated module before the normal distribution build.
 * @param {string} root Owning library checkout.
 * @param {object} manifest Authoritative public manifest.
 * @param {object} [options] Read-only drift check options.
 * @param {boolean} [options.check=false] Refuse drift without writing.
 * @returns {void} Completes with exact bytes or a bounded drift error.
 */
export function syncGuidedCorners(root, manifest, { check = false } = {}) {
  const target = path.join(root, 'styles/guided-corners.css');
  const expected = guidedCornersCss(manifest);
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
  if (current === expected) return;
  if (check) throw new Error('Guided corner CSS is stale. Run the owning library build.');
  fs.writeFileSync(target, expected);
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = process.cwd();
  syncGuidedCorners(root, JSON.parse(fs.readFileSync(path.join(root, 'manifest.json'), 'utf8')), {
    check: process.argv.includes('--check'),
  });
}
